// Builds supabase/03_seed.sql from data/*.json, so the database starts with exactly what Stage 1 shows.
// Run: npm run db:seed   (writes the file; you paste it into the Supabase SQL Editor).
// Every JSON key must map to a column, or this script stops: nothing is silently dropped.

import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => JSON.parse(readFileSync(new URL(`../data/${name}.json`, import.meta.url), "utf8"));

// table, source file, primary key, column types (anything not listed is plain text/number/boolean),
// renamed keys (JSON key → column), and extra columns every seeded row gets.
const SAMPLE = { published: true, origin: "sample" };
const TABLES = [
  { table: "fields", file: "fields", pk: "slug", rename: { group: "field_group" }, extra: { published: true } },
  { table: "degree_mappings", file: "degree-mapping", pk: "slug", extra: { published: true } },
  { table: "exchange_rates", file: "exchange-rates", pk: "currency", extra: SAMPLE },
  { table: "glossary_terms", file: "glossary", pk: "slug", extra: SAMPLE },
  { table: "countries", file: "countries", pk: "slug", jsonb: ["photo"], extra: SAMPLE },
  { table: "cities", file: "cities", pk: "slug", jsonb: ["photo", "common_student_jobs", "job_search_links"], extra: SAMPLE },
  { table: "universities", file: "universities", pk: "slug", jsonb: ["ranking"], extra: SAMPLE },
  {
    table: "programs",
    file: "programs",
    pk: "slug",
    jsonb: ["intakes", "min_gpa_requirement", "english_tests"],
    arrays: ["required_documents", "related_bachelor_fields", "career_paths_en", "career_paths_bn"],
    extra: SAMPLE,
  },
  {
    table: "scholarships",
    file: "scholarships",
    pk: "slug",
    jsonb: ["coverage"],
    arrays: ["levels", "evaluates", "countries", "universities", "programs"],
    extra: SAMPLE,
  },
];

// Columns that exist in 01_schema.sql, per table (kept here so a typo in the JSON fails loudly).
const schema = readFileSync(new URL("../supabase/01_schema.sql", import.meta.url), "utf8");
function columnsOf(table) {
  const block = schema.match(new RegExp(`create table if not exists public\\.${table} \\(([\\s\\S]*?)\\n\\);`));
  if (!block) throw new Error(`No table ${table} in 01_schema.sql`);
  return new Set(
    block[1]
      .split("\n")
      .map((line) => line.trim().match(/^([a-z_0-9]+)\s/)?.[1])
      .filter((c) => c && c !== "constraint"),
  );
}

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`;
function literal(value, kind) {
  if (value === null || value === undefined) return "null";
  if (kind === "jsonb") return `${quote(JSON.stringify(value))}::jsonb`;
  if (kind === "array") {
    if (!Array.isArray(value)) throw new Error(`Expected an array, got ${JSON.stringify(value)}`);
    return value.length ? `array[${value.map(quote).join(", ")}]::text[]` : `'{}'::text[]`;
  }
  if (typeof value === "boolean" || typeof value === "number") return String(value);
  if (typeof value === "object") throw new Error(`Nested value needs a jsonb or array column: ${JSON.stringify(value)}`);
  return quote(value);
}

// --tables fields,glossary_terms --out file.sql: only those tables (e.g. reference data without the sample places).
const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const only = arg("tables")?.split(",");
if (only) TABLES.splice(0, TABLES.length, ...TABLES.filter((t) => only.includes(t.table)));
const outFile = arg("out");

let sql = `-- amarAbroad database, part 3 of 3: the Stage 1 sample data.
-- Generated by scripts/build-seed.mjs from data/*.json. Don't edit by hand: change the JSON and run npm run db:seed.
-- Paste into Supabase → SQL Editor → Run, after 01 and 02. Safe to run again (rows are updated in place).

begin;
`;
let total = 0;

for (const t of TABLES) {
  const rows = read(t.file);
  const columns = columnsOf(t.table);
  const kinds = Object.fromEntries([...(t.jsonb ?? []).map((c) => [c, "jsonb"]), ...(t.arrays ?? []).map((c) => [c, "array"])]);
  const keys = [...new Set(rows.flatMap((r) => Object.keys(r)))].map((k) => t.rename?.[k] ?? k);
  const cols = [...keys, ...Object.keys(t.extra)];
  for (const c of cols) if (!columns.has(c)) throw new Error(`${t.table}: data has "${c}" but the table has no such column`);

  const values = rows.map((r) => {
    const row = { ...Object.fromEntries(Object.entries(r).map(([k, v]) => [t.rename?.[k] ?? k, v])), ...t.extra };
    return `  (${cols.map((c) => literal(row[c], kinds[c])).join(", ")})`;
  });
  const updates = cols.filter((c) => c !== t.pk).map((c) => `${c} = excluded.${c}`);
  sql += `\n-- ${t.table}: ${rows.length} rows\ninsert into public.${t.table} (${cols.join(", ")}) values\n${values.join(",\n")}\non conflict (${t.pk}) do update set ${updates.join(", ")};\n`;
  total += rows.length;
}

sql += "\ncommit;\n";
writeFileSync(outFile ?? new URL("../supabase/03_seed.sql", import.meta.url), sql);
console.log(`Wrote ${outFile ?? "supabase/03_seed.sql"}: ${total} rows in ${TABLES.length} tables.`);
